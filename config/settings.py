def _env_bool(name, default=False):
    value = os.environ.get(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


def _env_int(name, default, minimum=0):
    """A whole-number setting. A typo stops startup with a clear message, not a bare ValueError."""
    raw = os.environ.get(name, "").strip() or str(default)
    if not re.fullmatch(r"[0-9]+", raw) or int(raw) < minimum:
        raise ImproperlyConfigured(f"{name} must be a whole number of {minimum} or more.")
    return int(raw)


def _weak_secret_key(key):
    """The same test as Django's security.W009 check, plus common placeholders."""
    return (
        len(key) < 50
        or len(set(key)) < 5
        or key.startswith("django-insecure-")
        or key.lower().startswith(("replace-with", "changeme", "change-me"))
    )


