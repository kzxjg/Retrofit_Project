    SECURE_REDIRECT_EXEMPT = [r'^api/health$']
    SESSION_COOKIE_SECURE = True
    CSRF_COOKIE_SECURE = True
    SECURE_HSTS_SECONDS = _env_int('DJANGO_SECURE_HSTS_SECONDS', 31536000)
    if SECURE_HSTS_SECONDS:
        SECURE_HSTS_INCLUDE_SUBDOMAINS = True
        SECURE_HSTS_PRELOAD = True
    # Only trust a proxy's "this was HTTPS" header when the app is actually behind
    # a trusted AWS ALB/CloudFront proxy. Do not enable this for a directly exposed app.
    # Which header: X-Forwarded-Proto (set by the ALB) normally. Use
    # CloudFront-Forwarded-Proto when CloudFront reaches the ALB over plain HTTP,
    # as it must before there is a domain to get the ALB a certificate for; the
    # ALB then says "http" and only CloudFront knows the visitor used HTTPS.
    if _env_bool('DJANGO_TRUST_PROXY_HEADERS', False):
        _proto_header = os.environ.get('DJANGO_PROXY_SSL_HEADER', '').strip() or 'X-Forwarded-Proto'
        if _proto_header.lower() not in {'x-forwarded-proto', 'cloudfront-forwarded-proto'}:
            raise ImproperlyConfigured(
                "DJANGO_PROXY_SSL_HEADER must be X-Forwarded-Proto or CloudFront-Forwarded-Proto."
            )
        SECURE_PROXY_SSL_HEADER = ('HTTP_' + _proto_header.upper().replace('-', '_'), 'https')


