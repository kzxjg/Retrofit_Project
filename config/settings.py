# The public hostname(s) visitors use. Before there is a domain, that is the
# CloudFront one (d1234abcd.cloudfront.net); add the real domain later, comma-
# separated (DEPLOY.md lists the steps). Load balancer health checks need no entry.
_hosts = [host.strip() for host in os.environ.get("DJANGO_ALLOWED_HOSTS", "").split(",") if host.strip()]
if not _hosts and not DEBUG:
    # Without it every request but the health check would get 400 while the
    # load balancer still reported the app healthy. Fail loudly instead.
    raise ImproperlyConfigured(
        "DJANGO_ALLOWED_HOSTS must be set when DJANGO_DEBUG is false, e.g. to the "
        "CloudFront address d1234abcd.cloudfront.net until there is a domain."
    )
ALLOWED_HOSTS = _hosts or ["localhost", "127.0.0.1", "[::1]"]
for _host in ALLOWED_HOSTS:
    if _host == "*" or "://" in _host or "/" in _host:
        raise ImproperlyConfigured(
            f"DJANGO_ALLOWED_HOSTS entry {_host!r} is not a hostname: list names only, "
            "like retrofit.example.com, without https:// or a path, and not *."
        )

