# The cache holds the rate-limit counts. Without DJANGO_REDIS_URL it is each
# process's own memory, so with N processes a visitor gets N times the limit;
# `check --deploy` warns about that. On AWS, point it at ElastiCache (Redis or
# Valkey). Production requires rediss:// (TLS), as it requires TLS to the database.
REDIS_URL = os.environ.get('DJANGO_REDIS_URL', '').strip()
if REDIS_URL:
    if not REDIS_URL.startswith(('redis://', 'rediss://')):
        raise ImproperlyConfigured("DJANGO_REDIS_URL must start with redis:// or rediss://.")
    if not DEBUG and not REDIS_URL.startswith('rediss://'):
        raise ImproperlyConfigured("DJANGO_REDIS_URL must use rediss:// (TLS) in production.")
    CACHES = {
        'default': {
            'BACKEND': 'django.core.cache.backends.redis.RedisCache',
            'LOCATION': REDIS_URL,
            'KEY_PREFIX': 'retrofit',
            # Give up quickly if Redis is unreachable instead of holding the request open.
            'OPTIONS': {'socket_connect_timeout': 2, 'socket_timeout': 2},
        },
    }
else:
    CACHES = {'default': {'BACKEND': 'django.core.cache.backends.locmem.LocMemCache'}}

# How many trusted proxies sit in front of Django and append to X-Forwarded-For.
# 0: clients connect directly, so rate-limit on REMOTE_ADDR. 1: behind an ALB.
# 2: CloudFront in front of an ALB. Too high lets clients fake their address;
# too low (0 behind a proxy) puts every user in one shared allowance.
TRUSTED_PROXY_COUNT = _env_int('DJANGO_TRUSTED_PROXY_COUNT', 0)

